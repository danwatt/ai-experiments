#!/usr/bin/env python3
"""Render script.json to narration.mp3 + narration.js with Voicebox (local TTS server).

One clip per sentence, concatenated with short gaps, so captions have exact timings.
Usage: python3 build_narration.py [--voice Heart] [--url http://127.0.0.1:17493]
Needs ffmpeg/ffprobe on PATH.
"""
import argparse, json, subprocess, time, urllib.request, hashlib
from pathlib import Path

HERE = Path(__file__).parent
SENT_GAP, SCENE_GAP, LEAD = 0.35, 0.9, 0.4
RATE = 24000


def api(base, method, path, body=None):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(base + path, data=data, method=method, headers={"content-type": "application/json"})
    with urllib.request.urlopen(req, timeout=600) as r:
        raw = r.read()
    return json.loads(raw) if raw else None


def tts(base, profile, text, dest):
    gen = api(base, "POST", "/generate", {"profile_id": profile["id"], "text": text, "language": "en",
                                          "engine": profile.get("default_engine") or profile.get("preset_engine")})
    while gen["status"] not in ("completed", "failed", "cancelled", "error"):
        time.sleep(0.5)
        gen = api(base, "GET", f"/history/{gen['id']}")
    if gen["status"] != "completed":
        raise RuntimeError(gen.get("error") or gen["status"])
    with urllib.request.urlopen(f"{base}/audio/{gen['id']}", timeout=600) as r:
        dest.write_bytes(r.read())
    api(base, "DELETE", f"/history/{gen['id']}")


def duration(p):
    out = subprocess.check_output(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(p)])
    return float(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--voice", default="Heart")
    ap.add_argument("--url", default="http://127.0.0.1:17493")
    a = ap.parse_args()
    profile = next(p for p in api(a.url, "GET", "/profiles") if p["name"] == a.voice)
    clips = HERE / "audio" / "clips"
    clips.mkdir(parents=True, exist_ok=True)
    scenes = json.loads((HERE / "script.json").read_text())

    parts, t = [], LEAD
    parts.append(("silence", LEAD))
    out_scenes = []
    for si, sc in enumerate(scenes):
        start = t - (LEAD if si == 0 else SCENE_GAP / 2)
        sents = []
        for li, line in enumerate(sc["lines"]):
            key = hashlib.sha1(f"{a.voice}|{line}".encode()).hexdigest()[:12]
            wav = clips / f"{key}.wav"
            if not wav.exists():
                print("tts:", line[:60])
                tts(a.url, profile, line, wav)
            d = duration(wav)
            sents.append({"text": line, "start": round(t, 3), "end": round(t + d, 3)})
            parts.append(("clip", wav))
            t += d
            gap = SENT_GAP if li < len(sc["lines"]) - 1 else SCENE_GAP
            parts.append(("silence", gap))
            t += gap
        out_scenes.append({"id": sc["id"], "title": sc["title"], "start": round(max(0, start), 3), "sentences": sents})
    for i, sc in enumerate(out_scenes):
        sc["end"] = out_scenes[i + 1]["start"] if i + 1 < len(out_scenes) else round(t, 3)

    # concat via ffmpeg filter graph: every part resampled to mono RATE
    args, filt = ["ffmpeg", "-y", "-v", "error"], []
    for kind, v in parts:
        if kind == "clip":
            args += ["-i", str(v)]
        else:
            args += ["-f", "lavfi", "-t", f"{v:.3f}", "-i", f"anullsrc=r={RATE}:cl=mono"]
    for i in range(len(parts)):
        filt.append(f"[{i}:a]aresample={RATE},aformat=channel_layouts=mono[a{i}]")
    filt.append("".join(f"[a{i}]" for i in range(len(parts))) + f"concat=n={len(parts)}:v=0:a=1[out]")
    args += ["-filter_complex", ";".join(filt), "-map", "[out]", "-c:a", "libmp3lame", "-b:a", "96k", str(HERE / "audio" / "narration.mp3")]
    subprocess.check_call(args)

    data = {"voice": f"Voicebox · Kokoro {profile.get('preset_voice_id')}", "duration": round(t, 3), "scenes": out_scenes}
    (HERE / "narration.js").write_text("// Generated by build_narration.py from script.json. Do not edit by hand.\nwindow.NARRATION = "
                                       + json.dumps(data, indent=1) + ";\n")
    print(f"total {t:.1f}s, real mp3 {duration(HERE / 'audio' / 'narration.mp3'):.1f}s")


if __name__ == "__main__":
    main()
