#!/usr/bin/env python3
"""Build data.js: annual US stock, bond, bill and inflation series.

1928+ : Aswath Damodaran, histretSP.xls (S&P 500 incl. dividends, 3-month T-bill,
        10-year T-bond, CPI inflation; calendar years).
1872-1927 : Robert Shiller, ie_data.xls (monthly S&P composite total return,
        GS10 total bond return, CPI); converted to December-to-December years.
CAPE (P/E10) for January of every year, and the latest month, also from Shiller.

Usage: python3 build-data.py [histretSP.xls ie_data.xls]   (downloads them if omitted)
"""
import json, re, sys, tempfile, urllib.request, os
import pandas as pd

DAMODARAN = "https://pages.stern.nyu.edu/~adamodar/pc/datasets/histretSP.xls"
SHILLER_PAGE = "https://shillerdata.com/"


def shiller_url():
    html = urllib.request.urlopen(SHILLER_PAGE).read().decode("utf-8", "replace")
    m = re.search(r'href="([^"]*/ie_data\.xls[^"]*)"', html)
    if not m:
        sys.exit("ie_data.xls link not found on " + SHILLER_PAGE)
    return ("https:" + m.group(1)) if m.group(1).startswith("//") else m.group(1)


def fetch(url, d):
    p = os.path.join(d, url.split("?")[0].rsplit("/", 1)[1])
    urllib.request.urlretrieve(url, p)
    return p


def damodaran(path):
    df = pd.read_excel(path, sheet_name="Returns by year", header=None)
    r = df.iloc[20:, [0, 1, 3, 4, 20]]
    r = r[pd.to_numeric(r[0], errors="coerce").notna()]
    out = {}
    for y, s, bill, bond, cpi in r.itertuples(index=False):
        out[int(y)] = dict(s=float(s), b=float(bond), t=float(bill), i=float(cpi), src="D")
    return out


def shiller(path):
    d = pd.read_excel(path, sheet_name="Data", header=None).iloc[8:]
    d = d[pd.to_numeric(d[0], errors="coerce").notna()]
    d = d[[0, 4, 6, 9, 18, 12]].astype(float)
    d.columns = ["date", "cpi", "gs10", "rtr", "rbond", "cape"]
    d["year"] = (d.date + 1e-6).astype(int)
    d["mon"] = ((d.date - d.year) * 100 + 0.5).astype(int)
    dec = d[d.mon == 12].set_index("year")
    out = {}
    for y in range(1872, 1928):
        a, b = dec.loc[y - 1], dec.loc[y]
        infl = b.cpi / a.cpi - 1
        stock = (b.rtr * b.cpi) / (a.rtr * a.cpi) - 1
        bond = (b.rbond * b.cpi) / (a.rbond * a.cpi) - 1
        out[y] = dict(s=stock, b=bond, t=float(a.gs10) / 100 * 0.8, i=infl, src="S")
    # sanity check against Damodaran's 1928
    a, b = dec.loc[1927], dec.loc[1928]
    print("Shiller 1928 stock", round((b.rtr * b.cpi) / (a.rtr * a.cpi) - 1, 4), file=sys.stderr)
    jan = d[d.mon == 1].set_index("year").cape.dropna()
    cape = {int(y): float(v) for y, v in jan.items()}
    latest = d.dropna(subset=["cape"]).iloc[-1]
    now = dict(cape=round(float(latest.cape), 1), year=int(latest.year), month=int(latest.mon))
    # consumer prices in January of each year, and in the latest month, to turn
    # "today's dollars" back into the dollars people actually deposited
    cpi_jan = {int(y): float(v) for y, v in d[d.mon == 1].set_index("year").cpi.dropna().items()}
    last_cpi = d.dropna(subset=["cpi"]).iloc[-1]
    now["cpi"] = round(float(last_cpi.cpi), 3)
    now["cpiYear"], now["cpiMonth"] = int(last_cpi.year), int(last_cpi.mon)
    return out, cape, now, cpi_jan


def main():
    if len(sys.argv) == 3:
        dp, sp = sys.argv[1:]
    else:
        tmp = tempfile.mkdtemp()
        dp, sp = fetch(DAMODARAN, tmp), fetch(shiller_url(), tmp)
    early, cape, now, cpi_jan = shiller(sp)
    rows = {**early, **damodaran(dp)}
    years = sorted(rows)
    data = {
        "first": years[0],
        "last": years[-1],
        "damodaranFirst": 1928,
        "stocks": [round(rows[y]["s"], 5) for y in years],
        "bonds": [round(rows[y]["b"], 5) for y in years],
        "infl": [round(rows[y]["i"], 5) for y in years],
        # CAPE in January of each year (the valuation on retirement day); null before 1881
        "cape": [round(cape[y], 2) if y in cape else None for y in years],
        "capeNow": now,
        # CPI in January of each year (Shiller), for converting today's dollars to the dollars of the time
        "cpiJan": [round(cpi_jan[y], 3) if y in cpi_jan else None for y in years],
    }
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "data.js"), "w") as f:
        f.write("// Generated by build-data.py. Annual nominal returns (decimal), index 0 = first.\n")
        f.write("window.HIST = " + json.dumps(data, separators=(",", ":")) + ";\n")
    print(f"{years[0]}-{years[-1]}: {len(years)} years", file=sys.stderr)


main()
