#define ATLAS_W 128
#define ATLAS_H 48

/* Builds the atlas in a scratch buffer; returns pixels (ATLAS_W x ATLAS_H). */
static u16 atlas[ATLAS_W * ATLAS_H];

const u16 *font_atlas(void)
{
    int i, x, y;
    memset(atlas, 0, sizeof(atlas));
    for (i = 0; i < 64; i++) {
        int ox = (i & 15) * 8, oy = (i >> 4) * 8;
        for (x = 0; x < 5; x++)
            for (y = 0; y < 7; y++)
                if (font_small[i][x] & (1 << y))
                    atlas[(oy + y) * ATLAS_W + ox + x] = 0x7FFF;
    }
    for (i = 0; i < 10; i++) {
        int ox = i * 10, oy = 32;
        for (y = 0; y < 10; y++)
            for (x = 0; x < 8; x++)
                if (font_bold[i][y] & (0x80 >> x))
                    atlas[(oy + y) * ATLAS_W + ox + x] = 0x7FFF;
    }
    return atlas;
}
