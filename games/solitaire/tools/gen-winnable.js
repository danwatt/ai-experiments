// Prove deals winnable offline and write js/winnable.js.
//   node tools/gen-winnable.js [count=1000] [modes=all]
// Each worker deals random seeds for one mode and searches for a win using
// the game's own rules; every seed it reports was replayed to a win.
import { fork } from 'node:child_process';
import { writeFileSync, existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { MODES } from '../js/games/index.js';
import { solve, settle } from '../js/core/solver.js';
import { stagedSolve } from '../js/core/staged.js';

const SEARCH = {
  klondike1: (g, s) => solve(g, s, { maxNodes: 50000 }),
  klondike3: (g, s) => solve(g, s, { maxNodes: 50000 }),
  spider1: (g, s) => solve(g, s, { maxNodes: 50000 }),
  spider2: (g, s) => stagedSolve(g, s, { stageNodes: 4000, attempts: 4 }),
  freecell: (g, s) => solve(g, s, { maxNodes: 50000 }),
  pyramid: (g, s) => solve(g, s, { maxNodes: 50000 }),
  tripeaks: (g, s) => solve(g, s, { maxNodes: 50000 }),
};

if (process.argv[2] === '--worker') {
  const id = process.argv[3];
  const g = MODES[id];
  for (;;) {
    const seed = 1 + Math.floor(Math.random() * 999999998);
    const path = SEARCH[id](g, g.deal(seed));
    if (!path) continue;
    let r = g.deal(seed);
    for (const m of path) r = settle(g, g.apply(r, m));
    if (g.isWon(r)) process.send({ id, seed, len: path.length });
  }
} else {
  const target = +(process.argv[2] || 1000);
  const modes = process.argv[3] ? process.argv[3].split(',') : Object.keys(SEARCH);
  const out = new URL('../js/winnable.js', import.meta.url);
  const found = {};
  if (existsSync(out)) {
    const m = readFileSync(out, 'utf8').match(/=\s*(\{[\s\S]*\});/);
    if (m) Object.assign(found, JSON.parse(m[1]));
  }
  const weight = { spider2: 5, klondike1: 2, klondike3: 2, pyramid: 1, freecell: 1, tripeaks: 1, spider1: 1 };
  const self = fileURLToPath(import.meta.url);
  const workers = [];
  const write = () => {
    const body = JSON.stringify(found).replace(/\],/g, '],\n  ');
    writeFileSync(out, `// Generated by tools/gen-winnable.js. Every seed here was solved by search\n// using the game's own rules (Spider 4 suits is not covered).\nexport const WINNABLE = ${body};\n`);
  };
  const t0 = Date.now();
  for (const id of modes) {
    found[id] = found[id] || [];
    if (found[id].length >= target) continue;
    for (let k = 0; k < (weight[id] || 1); k++) {
      const w = fork(self, ['--worker', id]);
      workers.push({ id, w });
      w.on('message', (msg) => {
        const list = found[msg.id];
        if (list.length >= target || list.includes(msg.seed)) return;
        list.push(msg.seed);
        if (list.length % 100 === 0) {
          console.log(`${msg.id} ${list.length}/${target} after ${((Date.now() - t0) / 1000).toFixed(0)}s`);
          write();
        }
        if (list.length >= target) for (const x of workers) if (x.id === msg.id) x.w.kill();
        if (modes.every((m) => found[m].length >= target)) { write(); console.log('done'); process.exit(0); }
      });
    }
  }
}
