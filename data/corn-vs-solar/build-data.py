#!/usr/bin/env python3
"""Rebuild data.js: NASS corn yields by state + solar yield per kWdc by state.

Sources
- Corn: USDA NASS Crop Production 2025 Summary (cropan26.txt), corn-for-grain yield 2023-2025.
- Irradiance: Open-Meteo archive (ERA5) daily shortwave_radiation_sum, 2016-2025, at the
  farming-area point for each state in states.tsv.
- Solar yield: NLR (ex-NREL) PVWatts v8, single-axis tracking, 14% losses, DC/AC 1.3, GCR 0.35,
  run at 8 calibration points (CAL below, kWh AC per kWdc per year). Other states use a
  linear fit of those results on the Open-Meteo irradiance (within ~4% at the calibration points).
  PVWatts DEMO_KEY allows only 10 calls an hour, hence the fit.
"""
import json, re, urllib.request
from pathlib import Path

HERE = Path(__file__).parent
NASS = "https://esmis.nal.usda.gov/sites/default/release-files/795725/cropan26.txt"
CAL = {"AZ": 2137.98, "TX": 2075.43, "MN": 1528.19, "OH": 1515.59, "FL": 1747.49, "WA": 1629.67, "CO": 1816.07, "IA": 1601.34}

states = [l.split("\t") for l in (HERE / "states.tsv").read_text().strip().split("\n")]

txt = urllib.request.urlopen(NASS).read().decode("latin-1").split("\n")
start = next(i for i, l in enumerate(txt) if "Corn Area Planted for All Purposes" in l and "(continued)" in txt[i + 1])
yields = {}
for l in txt[start:start + 70]:
    m = re.match(r"([A-Za-z ]+?)[ .]*(?:1/)?[ .]*:\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([\d,]+)\s+([\d,]+)\s+([\d,]+)", l)
    if m:
        yields[m.group(1).strip()] = [float(m.group(i)) for i in (2, 3, 4)] + [int(m.group(7).replace(",", ""))]

lats = ",".join(s[2] for s in states); lons = ",".join(s[3] for s in states)
url = (f"https://archive-api.open-meteo.com/v1/archive?latitude={lats}&longitude={lons}"
       "&start_date=2016-01-01&end_date=2025-12-31&daily=shortwave_radiation_sum&timezone=UTC")
om = json.load(urllib.request.urlopen(url))
ghi = {}
for s, d in zip(states, om):
    v = [x for x in d["daily"]["shortwave_radiation_sum"] if x is not None]
    ghi[s[0]] = sum(v) / len(v) / 3.6 * 365.25  # MJ/m2/day -> kWh/m2/yr

xs = [ghi[k] for k in CAL]; ys = list(CAL.values()); n = len(xs)
mx, my = sum(xs) / n, sum(ys) / n
b = sum((x - mx) * (y - my) for x, y in zip(xs, ys)) / sum((x - mx) ** 2 for x in xs); a = my - b * mx

out = []
for ab, name, lat, lon in states:
    y = yields[name]
    out.append(dict(ab=ab, name=name, lat=float(lat), lon=float(lon),
                    corn={"2023": y[0], "2024": y[1], "2025": y[2]}, prod2025=y[3],
                    ghi=round(ghi[ab]), trk=round(CAL.get(ab, a + b * ghi[ab])), pvw=ab in CAL))
us = yields["United States"]
js = ("// Generated by build-data.py: NASS Crop Production 2025 Summary (Jan 2026) corn-for-grain yields, bu/acre; prod2025 in 1,000 bu.\n"
      "// ghi = Open-Meteo ERA5 archive 2016-2025 mean global horizontal irradiance at the point, kWh/m2/yr;\n"
      "// trk = single-axis-tracking AC yield, kWh per kWdc per yr: NLR PVWatts v8 where pvw=true, else regression on ghi fit to those points.\n")
js += "window.US_CORN = " + json.dumps({"2023": us[0], "2024": us[1], "2025": us[2]}) + ";\n"
js += "window.STATES = [\n" + ",\n".join("  " + json.dumps(o, separators=(",", ":")) for o in out) + "\n];\n"
(HERE / "data.js").write_text(js)
print(f"{len(out)} states; fit trk = {a:.1f} + {b:.4f} * ghi")
