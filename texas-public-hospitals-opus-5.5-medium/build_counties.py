#!/usr/bin/env python3
"""Build counties.js: Texas county outlines as SVG path strings.

Usage: python3 -I build_counties.py   (reads .sources/geo/counties-10m.json from fetch_sources.py)
Source: https://cdn.jsdelivr.net/npm/us-atlas@3.0.1/counties-10m.json (Census cartographic
boundaries, TopoJSON). Projects with an Albers equal-area conic fitted to Texas, simplifies
lightly (Douglas-Peucker, 0.6 px) and writes window.TX_COUNTIES = {viewBox, counties: {fips: {name, d}}}.
"""
import json, math, os, sys

topo = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".sources", "geo", "counties-10m.json")))
sx, sy = topo["transform"]["scale"]
tx, ty = topo["transform"]["translate"]

def decode(arc):
    x = y = 0
    pts = []
    for dx, dy in arc:
        x += dx; y += dy
        pts.append((x * sx + tx, y * sy + ty))
    return pts

ARCS = [decode(a) for a in topo["arcs"]]

# Albers equal-area conic for Texas
lat1, lat2, lat0, lon0 = map(math.radians, (27.5, 35.0, 31.0, -100.0))
n = (math.sin(lat1) + math.sin(lat2)) / 2
C = math.cos(lat1) ** 2 + 2 * n * math.sin(lat1)
rho0 = math.sqrt(C - 2 * n * math.sin(lat0)) / n

def proj(lon, lat):
    lon, lat = math.radians(lon), math.radians(lat)
    rho = math.sqrt(C - 2 * n * math.sin(lat)) / n
    th = n * (lon - lon0)
    return rho * math.sin(th), -(rho0 - rho * math.cos(th))

def ring(idx):
    pts = []
    for i in idx:
        a = ARCS[i] if i >= 0 else ARCS[~i][::-1]
        pts.extend(a if not pts else a[1:])
    return pts

def dp(pts, eps):
    if len(pts) < 4: return pts
    keep = [False] * len(pts); keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1
        L = math.hypot(dx, dy) or 1e-9
        best, bi = 0, None
        for i in range(a + 1, b):
            d = abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / L
            if d > best: best, bi = d, i
        if bi is not None and best > eps:
            keep[bi] = True; stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]

geoms = [g for g in topo["objects"]["counties"]["geometries"] if g["id"].startswith("48")]
rings = {}
for g in geoms:
    polys = g["arcs"] if g["type"] == "MultiPolygon" else [g["arcs"]]
    rings[g["id"]] = [[proj(*p) for p in ring(r)] for poly in polys for r in poly]

xs = [p[0] for rs in rings.values() for r in rs for p in r]
ys = [p[1] for rs in rings.values() for r in rs for p in r]
W = 900
k = W / (max(xs) - min(xs))
H = round((max(ys) - min(ys)) * k)
out = {}
for g in geoms:
    parts = []
    for r in rings[g["id"]]:
        pts = [((x - min(xs)) * k, (y - min(ys)) * k) for x, y in r]
        # a closed ring starts and ends on the same point, which breaks Douglas-Peucker: simplify two halves
        m = len(pts) // 2
        pts = dp(pts[:m + 1], 0.6)[:-1] + dp(pts[m:], 0.6)
        if len(pts) < 3: continue
        parts.append("M" + "L".join(f"{x:.1f},{y:.1f}" for x, y in pts) + "Z")
    out[g["id"]] = {"name": g["properties"]["name"], "d": "".join(parts)}

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "counties.js"), "w") as f:
    f.write("// Generated by build_counties.py from us-atlas@3.0.1 counties-10m.json (US Census cartographic boundaries).\n")
    f.write("window.TX_COUNTIES = " + json.dumps({"viewBox": f"0 0 {W} {H}", "counties": out}, separators=(",", ":")) + ";\n")
print(len(out), "counties,", os.path.getsize(os.path.join(here, "counties.js")) // 1024, "KB, viewBox", W, H)
