#!/usr/bin/env python3
"""Copy the reports in output/ into demo/, a static site for GitHub Pages, with an index page.

    uv run tx_lege.py SB17 --session 89R      # generate (or refresh) a report first
    python3 tools/build_demo.py               # then rebuild demo/ from every report in output/
"""

from __future__ import annotations

import html
import json
import re
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
OUT = HERE / "output"
DEMO = HERE / "demo"

PAGE = """<!doctype html><html lang=en><head><meta charset=utf-8>
<meta name=viewport content='width=device-width,initial-scale=1'><title>tx-lege reports</title><style>
:root{{--bg:#fbfaf7;--fg:#1d1d1b;--muted:#6b6a65;--line:#e4e1d8;--card:#fff;--accent:#7a4b13}}
@media (prefers-color-scheme:dark){{:root:not([data-theme=light]){{--bg:#171715;--fg:#ecebe6;--muted:#a19f97;
--line:#34332f;--card:#1f1f1c;--accent:#e0a35c}}}}
:root[data-theme=dark]{{--bg:#171715;--fg:#ecebe6;--muted:#a19f97;--line:#34332f;--card:#1f1f1c;--accent:#e0a35c}}
*{{box-sizing:border-box}}
body{{margin:0;background:var(--bg);color:var(--fg);font:15px/1.5 -apple-system,BlinkMacSystemFont,"Segoe UI",Inter,sans-serif}}
main{{max-width:860px;margin:0 auto;padding:32px 16px 80px}}
h1{{font:600 28px/1.2 Georgia,serif;margin:0 0 6px}}a{{color:var(--accent)}}.muted{{color:var(--muted)}}
.card{{display:block;background:var(--card);border:1px solid var(--line);border-radius:8px;padding:14px 16px;
margin:12px 0;text-decoration:none;color:inherit}}.card:hover{{border-color:var(--accent)}}
.card h2{{font:600 19px/1.3 Georgia,serif;margin:0 0 4px;color:var(--accent)}}.card p{{margin:4px 0}}
.stats{{font-size:13px;color:var(--muted)}}
</style></head><body><main>
<h1>tx-lege reports</h1>
<p class=muted>Full legislative histories of Texas bills: timeline, amendments, every record vote and how each
member voted, party defections, and bill text diffs. Generated by <a href="../README.html">tx-lege</a> from
Texas Legislature Online and the House and Senate journals; these are snapshots, not live data.</p>
{cards}
</main></body></html>
"""


def card(slug: str, rec: dict) -> str:
    bill, fields = rec["bill"], rec["bill"]["fields"]
    sponsors = ", ".join(re.sub(r"^[HS]:", "", s) for s in rec["sponsors"].values())
    stats = (f"{len(rec['actions'])} actions · {len(rec['amendments'])} amendments · "
             f"{len(rec['rollcalls'])} record votes · last action {fields.get('Last Action', '')}")
    return (f'<a class=card href="{slug}.html"><h2>{html.escape(bill["session_label"])} '
            f'{html.escape(bill["label"])}</h2><p>{html.escape(fields.get("Caption Text", ""))}</p>'
            f'<p class=muted>{html.escape(sponsors)}</p><p class=stats>{html.escape(stats)}</p></a>')


def main() -> None:
    if DEMO.exists():
        shutil.rmtree(DEMO)
    DEMO.mkdir()
    cards = []
    for bill_json in sorted(OUT.glob("*/bill.json")):
        slug = bill_json.parent.name
        shutil.copyfile(bill_json.parent / "report.html", DEMO / f"{slug}.html")
        cards.append(card(slug, json.loads(bill_json.read_text())))
        print(f"  demo/{slug}.html")
    (DEMO / "index.html").write_text(PAGE.format(cards="\n".join(cards)))
    print("  demo/index.html")


if __name__ == "__main__":
    main()
